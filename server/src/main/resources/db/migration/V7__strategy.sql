-- V7：组卷策略
CREATE TABLE IF NOT EXISTS exam_strategy (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(120) NOT NULL,
  bank_id      BIGINT,
  rules        VARCHAR(2000),
  total_score  DECIMAL(8,1) NOT NULL DEFAULT 0,
  pass_score   DECIMAL(8,1) NOT NULL DEFAULT 60,
  duration_sec INT          NOT NULL DEFAULT 1800,
  remark       VARCHAR(255),
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
