-- V1 基线：平台域（组织 / 用户 / 角色 / 菜单权限）
-- 说明：本迁移保持 H2(PostgreSQL 模式) 与 PostgreSQL 16 双兼容，
--      JSONB、部分唯一索引等 PG 专有特性放到后续 PG 专属迁移（V2+）。

CREATE TABLE IF NOT EXISTS sys_org (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id   BIGINT,
  name        VARCHAR(64)  NOT NULL,
  sort_no     INT          NOT NULL DEFAULT 0,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sys_user (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(64)  NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  name          VARCHAR(64)  NOT NULL,
  phone         VARCHAR(20),
  email         VARCHAR(120),
  org_id        BIGINT,
  status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
  last_login_at TIMESTAMP,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_sys_user_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS sys_role (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       VARCHAR(64) NOT NULL,
  name       VARCHAR(64) NOT NULL,
  remark     VARCHAR(255),
  created_at TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_sys_role_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS sys_user_role (
  user_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  PRIMARY KEY (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS sys_menu (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT,
  name      VARCHAR(64)  NOT NULL,
  path      VARCHAR(120),
  icon      VARCHAR(32),
  perm      VARCHAR(120),
  type      VARCHAR(16)  NOT NULL DEFAULT 'MENU',
  sort_no   INT          NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sys_role_menu (
  role_id BIGINT NOT NULL,
  menu_id BIGINT NOT NULL,
  PRIMARY KEY (role_id, menu_id)
);

CREATE INDEX IF NOT EXISTS idx_sys_menu_parent ON sys_menu (parent_id);
CREATE INDEX IF NOT EXISTS idx_sys_user_org ON sys_user (org_id);
