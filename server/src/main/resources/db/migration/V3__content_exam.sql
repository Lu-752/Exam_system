-- V3：内容生产 + 组卷 + 考试执行
-- 说明：options / answer / config 用 TEXT 存 JSON，切到 PostgreSQL 后改 JSONB（V4/PG 专属迁移）

CREATE TABLE IF NOT EXISTS question_bank (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(128) NOT NULL,
  level       VARCHAR(16),
  sort_no     INT          NOT NULL DEFAULT 0,
  recommended BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS question (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bank_id     BIGINT       NOT NULL,
  type        VARCHAR(16)  NOT NULL,
  stem        VARCHAR(2000) NOT NULL,
  options     VARCHAR(4000),
  answer      VARCHAR(1000),
  analysis    VARCHAR(2000),
  score       DECIMAL(6,2) NOT NULL DEFAULT 5,
  difficulty  VARCHAR(16),
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_question_bank ON question (bank_id);

CREATE TABLE IF NOT EXISTS paper (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(128) NOT NULL,
  bank_id    BIGINT,
  total_score DECIMAL(7,2) NOT NULL DEFAULT 0,
  pass_score DECIMAL(7,2) NOT NULL DEFAULT 60,
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS paper_item (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_id    BIGINT       NOT NULL,
  question_id BIGINT       NOT NULL,
  sort_no     INT          NOT NULL DEFAULT 0,
  score       DECIMAL(6,2) NOT NULL DEFAULT 5
);
CREATE INDEX IF NOT EXISTS idx_paper_item_paper ON paper_item (paper_id);

CREATE TABLE IF NOT EXISTS exam_plan (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(128) NOT NULL,
  paper_id     BIGINT       NOT NULL,
  start_at     TIMESTAMP    NOT NULL,
  end_at       TIMESTAMP    NOT NULL,
  duration_sec INT          NOT NULL DEFAULT 1800,
  pass_score   DECIMAL(7,2) NOT NULL DEFAULT 60,
  max_attempts INT          NOT NULL DEFAULT 1,
  config       VARCHAR(2000),
  status       VARCHAR(16)  NOT NULL DEFAULT 'PUBLISHED',
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS exam_attempt (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id      BIGINT       NOT NULL,
  user_id      BIGINT       NOT NULL,
  student_name VARCHAR(64),
  status       VARCHAR(16)  NOT NULL DEFAULT 'IN_PROGRESS',
  started_at   TIMESTAMP    NOT NULL,
  submitted_at TIMESTAMP,
  deadline_at  TIMESTAMP    NOT NULL,
  score        DECIMAL(7,2),
  passed       BOOLEAN,
  CONSTRAINT uk_attempt_plan_user UNIQUE (plan_id, user_id)
);

CREATE TABLE IF NOT EXISTS attempt_answer (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id  BIGINT       NOT NULL,
  question_id BIGINT       NOT NULL,
  answer      VARCHAR(2000),
  correct     BOOLEAN,
  score       DECIMAL(6,2),
  CONSTRAINT uk_answer_attempt_question UNIQUE (attempt_id, question_id)
);
CREATE INDEX IF NOT EXISTS idx_answer_attempt ON attempt_answer (attempt_id);
