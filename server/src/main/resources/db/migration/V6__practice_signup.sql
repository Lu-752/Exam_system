-- V6：练习记录 + 考试报名
CREATE TABLE IF NOT EXISTS practice_record (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL,
  question_id BIGINT       NOT NULL,
  bank_id     BIGINT,
  my_answer   VARCHAR(2000),
  correct     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_practice_user ON practice_record (user_id, question_id);
CREATE INDEX IF NOT EXISTS idx_practice_created ON practice_record (user_id, created_at);

CREATE TABLE IF NOT EXISTS exam_signup (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id      BIGINT       NOT NULL,
  user_id      BIGINT       NOT NULL,
  student_name VARCHAR(64),
  status       VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
  remark       VARCHAR(255),
  created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at  TIMESTAMP,
  CONSTRAINT uk_exam_signup UNIQUE (plan_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_signup_plan ON exam_signup (plan_id, status);
