-- V2：学员域
CREATE TABLE IF NOT EXISTS sys_student (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no         VARCHAR(32)  NOT NULL,
  name       VARCHAR(64)  NOT NULL,
  gender     VARCHAR(8),
  org_name   VARCHAR(64),
  phone      VARCHAR(20),
  level      VARCHAR(16),
  exam_count INT          NOT NULL DEFAULT 0,
  status     VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_sys_student_no UNIQUE (no)
);

CREATE INDEX IF NOT EXISTS idx_sys_student_org ON sys_student (org_name);
CREATE INDEX IF NOT EXISTS idx_sys_student_status ON sys_student (status);
