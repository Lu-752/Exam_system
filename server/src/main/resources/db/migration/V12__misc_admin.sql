-- V12：补齐 4 个辅助管理域（大纲 / 字典 / 系统参数 / 专区）
CREATE TABLE IF NOT EXISTS sys_outline (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(200) NOT NULL,
  category    VARCHAR(50),
  version     VARCHAR(20),
  content     TEXT,
  status      VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  sort_no     INT NOT NULL DEFAULT 0,
  created_at  TIMESTAMP,
  updated_at  TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_outline_status ON sys_outline (status);

CREATE TABLE IF NOT EXISTS sys_dict_item (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dict_type   VARCHAR(50) NOT NULL,
  code        VARCHAR(50) NOT NULL,
  label       VARCHAR(100) NOT NULL,
  item_value  VARCHAR(200),
  sort_no     INT NOT NULL DEFAULT 0,
  status      VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  remark      VARCHAR(500),
  created_at  TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_dict_type ON sys_dict_item (dict_type);

CREATE TABLE IF NOT EXISTS sys_config (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  param_key    VARCHAR(100) NOT NULL,
  param_value  VARCHAR(500),
  remark       VARCHAR(500),
  updated_at   TIMESTAMP,
  CONSTRAINT uk_config_key UNIQUE (param_key)
);

CREATE TABLE IF NOT EXISTS sys_zone (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(200) NOT NULL,
  zone_type   VARCHAR(30) NOT NULL DEFAULT 'NOTICE',
  link_url    VARCHAR(500),
  summary     VARCHAR(500),
  sort_no     INT NOT NULL DEFAULT 0,
  status      VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  created_at  TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_zone_type ON sys_zone (zone_type);
